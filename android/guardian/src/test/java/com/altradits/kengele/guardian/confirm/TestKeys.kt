package com.altradits.kengele.guardian.confirm

import com.altradits.kengele.message.MessageException
import com.altradits.kengele.message.Secp256k1
import java.io.File
import java.security.MessageDigest

/**
 * Made-up keys for guardian tests. Deterministic, so a failure reproduces;
 * never real keys.
 */
object TestKeys {
    /** Deterministic made-up private key. Retried with a suffix until valid. */
    fun testPriv(seed: String): ByteArray {
        var i = 0
        while (true) {
            val label = if (i == 0) seed else "$seed:$i"
            val cand = MessageDigest.getInstance("SHA-256")
                .digest("kengele-test/$label".toByteArray(Charsets.UTF_8))
            try {
                Secp256k1.publicKey(cand)
                return cand
            } catch (e: MessageException) {
                i++
            }
        }
    }

    fun testPub(seed: String): ByteArray = Secp256k1.publicKey(testPriv(seed))
}

/**
 * Shamir vectors generated by running Go's `shamir.Split`
 * (`src/test/resources/shamir-vectors.json`). Both the Go self-check and
 * these Kotlin tests combine the same shares, so the port cannot drift.
 */
object ShamirVectors {
    data class Vec(
        val name: String,
        val secret: ByteArray,
        val parts: Int,
        val threshold: Int,
        val shares: List<ByteArray>,
    )

    private val text: String = run {
        ShamirVectors::class.java.getResource("/shamir-vectors.json")?.readText()
            ?: sequenceOf(
                File("src/test/resources/shamir-vectors.json"),
                File("android/guardian/src/test/resources/shamir-vectors.json"),
            ).firstOrNull { it.isFile }?.readText()
            ?: throw AssertionError("shamir-vectors.json not found")
    }

    val all: List<Vec> = run {
        // Minimal reader for the known generator shape; no JSON dependency.
        val names = Regex("\"name\"\\s*:\\s*\"([^\"]+)\"").findAll(text).map { it.groupValues[1] }.toList()
        val secrets = Regex("\"secret_hex\"\\s*:\\s*\"([^\"]+)\"").findAll(text).map { it.groupValues[1] }.toList()
        val parts = Regex("\"parts\"\\s*:\\s*(\\d+)").findAll(text).map { it.groupValues[1].toInt() }.toList()
        val thresholds = Regex("\"threshold\"\\s*:\\s*(\\d+)").findAll(text).map { it.groupValues[1].toInt() }.toList()
        val shareBlocks = Regex("\"shares_hex\"\\s*:\\s*\\[(.*?)\\]", RegexOption.DOT_MATCHES_ALL)
            .findAll(text).map { block ->
                Regex("\"([0-9a-f]+)\"").findAll(block.groupValues[1]).map { it.groupValues[1] }.toList()
            }.toList()
        require(names.size == secrets.size && names.size == shareBlocks.size && names.isNotEmpty()) {
            "shamir-vectors.json has an unexpected shape"
        }
        names.indices.map { i ->
            Vec(names[i], Hex.fromHex(secrets[i]), parts[i], thresholds[i], shareBlocks[i].map { Hex.fromHex(it) })
        }
    }

    fun named(name: String): Vec = all.first { it.name == name }
}
