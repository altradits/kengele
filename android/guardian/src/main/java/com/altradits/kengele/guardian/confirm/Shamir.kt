package com.altradits.kengele.guardian.confirm

/** Every failure to rebuild a secret from Shamir shares. */
class ShamirException(message: String) : Exception(message)

/**
 * Shamir's secret sharing, combine side only: a Kotlin port of
 * `Combine` from OpenBao's `sdk/v2/helper/shamir` (MPL-2.0, the fork of the
 * code HashiCorp Vault has used for its unseal keys for years), which is what
 * `internal/confirm` splits the alert key with.
 *
 * Each share is the secret bytes plus a trailing x coordinate; combining any
 * threshold-sized subset with distinct coordinates rebuilds the secret by
 * Lagrange interpolation at x = 0 over GF(2^8).
 *
 * Byte compatibility with the Go side is pinned by the shared vectors in
 * `src/test/resources/shamir-vectors.json`, generated by running Go's
 * `shamir.Split`. Android-free so plain JUnit covers it.
 */
object Shamir {
    /**
     * Rebuilds the secret from at least two shares. Every share must have the
     * same length (at least 2 bytes: one secret byte plus the x coordinate)
     * and a distinct trailing x coordinate.
     */
    fun combine(parts: List<ByteArray>): ByteArray {
        if (parts.size < 2) {
            throw ShamirException("less than two parts cannot be used to reconstruct the secret")
        }
        val len = parts[0].size
        if (len < 2) throw ShamirException("parts must be at least two bytes")
        for (p in parts) {
            if (p.size != len) throw ShamirException("all parts must be the same length")
        }
        val xs = IntArray(parts.size) { parts[it][len - 1].toInt() and 0xFF }
        if (xs.toSet().size != xs.size) throw ShamirException("duplicate part detected")
        val ys = IntArray(parts.size)
        return ByteArray(len - 1) { idx ->
            for (i in parts.indices) ys[i] = parts[i][idx].toInt() and 0xFF
            interpolate(xs, ys, 0).toByte()
        }
    }

    /** Lagrange interpolation of the sample points at x, over GF(2^8). */
    private fun interpolate(xs: IntArray, ys: IntArray, x: Int): Int {
        var result = 0
        for (i in xs.indices) {
            var basis = 1
            for (j in xs.indices) {
                if (i == j) continue
                basis = mult(basis, div(x xor xs[j], xs[i] xor xs[j]))
            }
            result = result xor mult(ys[i], basis)
        }
        return result
    }

    private fun div(a: Int, b: Int): Int {
        require(b != 0) { "divide by zero" }
        if (a == 0) return 0
        return mult(a, inverse(b))
    }

    /** a^-1 == a^254 in GF(2^8); the short 11-multiply chain from OpenBao. */
    private fun inverse(a: Int): Int {
        var b = mult(a, a) // a^2
        var c = mult(a, b) // a^3
        b = mult(c, c) // a^6
        b = mult(b, b) // a^12
        c = mult(b, c) // a^15
        b = mult(b, b) // a^24
        b = mult(b, b) // a^48
        b = mult(b, c) // a^63
        b = mult(b, b) // a^126
        b = mult(a, b) // a^127
        return mult(b, b) // a^254
    }

    /** Branch-free GF(2^8) multiply, bits MSB-first as in OpenBao. */
    private fun mult(a: Int, b: Int): Int {
        var r = 0
        for (i in 7 downTo 0) {
            val maskB = if ((b shr i) and 1 != 0) 0xFF else 0
            val maskR = if ((r shr 7) and 1 != 0) 0xFF else 0
            r = (maskB and a) xor (maskR and 0x1B) xor ((r shl 1) and 0xFF)
        }
        return r
    }
}
